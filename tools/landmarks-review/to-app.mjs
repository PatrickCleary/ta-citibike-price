// Turn the review tool's "Copy kept as JSON" output into app/src/data/landmarks.ts.
//   node tools/landmarks-review/to-app.mjs kept.json
// With no argument it uses landmarks.js as-is (every candidate, stock names and emoji).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
let rows;
if (process.argv[2]) {
  rows = JSON.parse(readFileSync(process.argv[2], "utf8"));
} else {
  globalThis.window = {};
  await import(resolve(here, "landmarks.js"));
  rows = globalThis.window.LANDMARKS;
}

const boroughs = [...new Set(rows.map((r) => r.borough))];
const lines = [
  "// NYC landmarks shown on the map for orientation once the story is running.",
  "// GENERATED by tools/landmarks-review/to-app.mjs from the review tool's export —",
  "// edit names, emoji and positions there, not here. Tier: 1 = iconic, 2 = well",
  "// known, 3 = local anchor; Landmarks.tsx places tier 1 first when labels overlap.",
  "",
  "export interface Landmark {",
  "  id: string;",
  "  name: string;",
  "  emoji: string;",
  `  borough: ${boroughs.map((b) => JSON.stringify(b)).join(" | ")};`,
  "  tier: 1 | 2 | 3;",
  "  lon: number;",
  "  lat: number;",
  "}",
  "",
  "export const LANDMARKS: Landmark[] = [",
];
let cur = null;
for (const r of rows) {
  if (r.borough !== cur) { cur = r.borough; lines.push(`  // ${cur}`); }
  lines.push(`  { id: ${JSON.stringify(r.id)}, name: ${JSON.stringify(r.name)}, emoji: ${JSON.stringify(r.emoji)}, borough: ${JSON.stringify(r.borough)}, tier: ${r.tier}, lon: ${r.lng}, lat: ${r.lat} },`);
}
lines.push("];", "");
const out = resolve(here, "../../app/src/data/landmarks.ts");
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${rows.length} landmarks to ${out}`);
